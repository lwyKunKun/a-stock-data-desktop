def _safe_category(value: str) -> str:
    cleaned = re.sub(r'[\\/:*?"<>|]', "-", (value or "").strip())
    return cleaned.strip(". ") or "未分类"


def resolve_category(profile: dict, concept_tags: list[str]) -> str:
    industry = str((profile or {}).get("industry") or "")
    haystack = " ".join([industry, *(str(tag) for tag in concept_tags or [])]).lower()
    for keywords, category in CATEGORY_RULES:
        if any(keyword.lower() in haystack for keyword in keywords):
            return category
    return _safe_category(industry)
